    private void btnVenderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVenderActionPerformed
    
    int itemSelecionado = listaProdutos.getSelectedRow();
    if (itemSelecionado == -1) {
        JOptionPane.showMessageDialog(null, "Selecione um produto para vender.");
        return;
    }
  
    ProdutosDTO produto = listagem.get(itemSelecionado);

    if ("Vendido".equals(produto.getStatus())) {
        JOptionPane.showMessageDialog(null, "Este produto já foi vendido.");
        return;
    }

    ProdutosDAO produtosdao = new ProdutosDAO();
    boolean sucesso = produtosdao.venderProduto(produto.getId());

    if (sucesso) {
        JOptionPane.showMessageDialog(this, "Produto vendido com sucesso!", "Sucesso",
                JOptionPane.INFORMATION_MESSAGE);
    } else {
        JOptionPane.showMessageDialog(this, "Não foi possível vender o produto.", "Erro",
                JOptionPane.ERROR_MESSAGE);
    }

    listarProdutos();

    }//GEN-LAST:event_btnVenderActionPerformed

